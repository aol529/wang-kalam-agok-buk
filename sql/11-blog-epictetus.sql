Seneca was one of the richest men in Rome. Epictetus started life as somebody else's property. Of all the Stoics, he had the least control over his own life, and he became the one who taught most clearly what we *can* control. Three of his books are now in the Library: the *Enchiridion*, the *Discourses* and the *Golden Sayings*. This is the man behind them.

**Born "acquired"**

Epictetus was born around AD 50–55 in Hierapolis, a Greek city in Phrygia: today's Pamukkale in south-west Turkey, famous for its white terraces of hot springs. We don't know his real name. *Epiktētos* is simply the Greek word for "acquired", the kind of label given to a slave. Nothing is known of his parents.

He was brought to Rome as the slave of Epaphroditus, a freedman who had risen to be one of Nero's secretaries, handling petitions to the emperor. It was a household at the centre of power, and of danger: in AD 68 Epaphroditus helped Nero take his own life as the Senate turned against him, and years later the emperor Domitian had Epaphroditus put to death for it. Epictetus saw from the inside how little wealth and favour at court are worth. His *Discourses* are full of rich men kissing the hands of other men's slaves for a favour.

**The leg**

Epictetus was lame, and walked with a limp all his life. The best-known story of how it happened comes from Celsus, a second-century writer quoted by Origen: his master was twisting his leg, and Epictetus calmly warned him it would break. When it broke, he said only, "There, did I not tell you it would break?" The story may be a legend. The Suda, a Byzantine encyclopedia, puts it down to rheumatism, and the 19th-century translator George Long doubted the broken-leg story. Either way, listen to how he talks about it in the *Discourses*:

"I must be put in chains. Must I then also lament? ... 'But I will put you in chains.' Man, what are you talking about? Me in chains? You may fetter my leg, but my will not even Zeus himself can overpower."

**A slave in the classroom**

While still a slave, with his master's permission, he studied under Musonius Rufus, the leading Stoic teacher in Rome, a man who was himself exiled more than once for his outspokenness. Some time later, probably after Nero's death, Epictetus was freed and began teaching philosophy in Rome on his own account.

Then the emperor came for the philosophers. Around AD 89 (some date it to the 90s) Domitian, suspicious of anyone teaching freedom of mind, banished philosophers from Rome and Italy. Epictetus moved across the Adriatic to Nicopolis in Epirus, on the north-west coast of Greece, a busy city on the road between Rome and the East.

**The school at Nicopolis**

There he opened the school he ran for the rest of his life, and it became famous. Young men from good Roman families came to study, and visitors stopped on their way through. Origen, writing a century later, says Epictetus was more widely read in his day than Plato. Herodes Atticus, the great orator and teacher of Marcus Aurelius, called him the greatest of the Stoics. A late Roman source, the *Historia Augusta* (not always reliable), even says the emperor Hadrian counted him among his friends.

He didn't think of his school as a pleasant place. "The philosopher's school, ye men, is a surgery: you ought not to go out of it with pleasure, but with pain." You came in sick, with false ideas about what's good and bad, and he went to work on them.

He lived as he taught, owning next to nothing. He tells how he once kept an iron lamp by his household gods, and when a thief stole it he shrugged it off: "To-morrow, I said, you will find an earthen lamp: for a man only loses that which he has." The satirist Lucian adds the punchline: after Epictetus died, someone paid three thousand drachmas for that cheap clay lamp, hoping some of the wisdom would rub off on him.

He never married. But Simplicius, a later commentator, says that when a friend was going to abandon his baby because he was too poor to raise it, Epictetus, who had lived alone for a long time, took the child in and brought it up, with a woman to nurse it.

He died around AD 135, aged about eighty.

**How his words survived**

Like Socrates, Epictetus wrote nothing. We have him because one of his students, Lucius Flavius Arrian, wrote down his lectures as nearly word for word as he could. Arrian later became a senator, governor of Cappadocia under Hadrian, and the historian of Alexander the Great.

- **The Discourses**: Arrian's notes of the lectures and conversations, rough and lively, in everyday Greek. There were at least eight books; four survive.
- **The Enchiridion**, "the handbook": Arrian's short summary of the essentials, meant to be kept at hand (the Greek word can also mean a hand-dagger). The best place to start.
- **The Golden Sayings**: not an ancient book but Hastings Crossley's 1903 selection of the best passages from the *Discourses*, with fragments from the lost books.

Not long after Epictetus died, a young man named Marcus was lent a copy of these "memoirs of Epictetus" by his teacher Junius Rusticus, from his own library. Marcus Aurelius became emperor and, in the *Meditations*, quotes Epictetus more than any other writer. The slave from Hierapolis became the teacher of an emperor he never met.

**What he taught, in one breath**

The first line of the *Enchiridion* is the whole philosophy: "There are things which are within our power, and there are things which are beyond our power." Our opinions, aims, desires and aversions are ours. Our body, property, reputation and position are not, not completely. Suffering comes from mixing them up: wanting what isn't ours to control, and neglecting what is.

**Five things worth taking from him**

1. **Sort everything into two piles.** Before you worry, ask: is this in my power or not? If it is, act. If not, it's "nothing to me", in his phrase. It's the Necessity and Personal Leadership boxes on the Vision board, but for the mind.

2. **It's your view, not the thing.** "Men are disturbed not by things, but by the views which they take of things." Change the judgment and you change the feeling. In the 1950s the psychologist Albert Ellis built rational emotive therapy, a forerunner of today's CBT, on exactly this line.

3. **Want what happens.** "Demand not that events should happen as you wish; but wish them to happen as they do happen, and you will go on well."

4. **Play your part well.** "Remember that you are an actor in a drama of such sort as the Author chooses." You don't pick the role (slave or emperor, healthy or lame), only how well you play it.

5. **Blame no one.** The beginner blames others, the learner blames himself, and the one who has learned blames neither.

**Why he still matters**

The *Enchiridion* was adapted for Christian monks in late antiquity, read by Pascal, and carried by Frederick the Great on campaign. In 1965 the American pilot James Stockdale was shot down over Vietnam and spent seven and a half years as a prisoner of war, much of it in solitary confinement and under torture. He said it was the *Enchiridion*, which he had read at university, that got him through: they could take everything except his own judgments and his will.

That's Epictetus's gift. He didn't teach from comfort. He taught from a broken leg, a borrowed name and an iron lamp that got stolen: whatever is done to you, the part that is really you is still yours.

*His three books are in the Library. Start with the Enchiridion: about forty minutes.*
